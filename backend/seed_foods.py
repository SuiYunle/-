def seed():
    with app.app_context():
        # 检查是否已初始化
        existing = FoodCategory.query.count()
        if existing > 0:
            print(f'数据库已有 {existing} 个分类，跳过初始化')
            return

        print('正在创建食物分类...')
        cat_map = {}
        for c in CATEGORIES:
            cat = FoodCategory(name=c['name'], display_name=c['display_name'], sort_order=c['sort_order'])
            db.session.add(cat)
            db.session.flush()
            cat_map[c['name']] = cat.id
            print(f'  分类: {c["name"]}')

        print(f'\n正在插入食物数据（共 {len(FOODS)} 条）...')
        count = 0
        for f in FOODS:
            name, cal, protein, fat, carbs, fiber, nature, flavor, meridian, func, tags, suitable, avoid, meals, desc = f
            item = FoodItem(
                name=name,
                category_id=cat_map.get(_get_category(name, tags, meals), cat_map['素菜']),
                calories=cal,
                protein=protein,
                fat=fat,
                carbs=carbs,
                fiber=fiber,
                tcm_nature=nature,
                tcm_flavor=flavor,
                tcm_meridian=meridian,
                tcm_function=func,
                tags=tags,
                suitable_constitutions=suitable,
                avoid_constitutions=avoid,
                meal_types=meals,
                description=desc,
                serving_size=100,
                serving_unit='g',
                is_active=True,
            )
            db.session.add(item)
            count += 1

        db.session.commit()
        print(f'\n完成！共插入 {count} 条食物数据')


def _get_category(name, tags, meals):
    """根据名称和标签推断分类"""
    tag_list = tags.split(',') if tags else []
    meal_list = meals.split(',') if meals else []

    if '汤品' in tag_list or '汤' in name or '羹' in name:
        return '汤羹'
    if '茶饮' in tag_list or '饮品' in tag_list:
        return '饮品'
    if '水果' in tag_list:
        return '水果'
    if '零食' in tag_list:
        return '零食'
    if '主食' in tag_list or '粥' in name or '饭' in name or '面' in name or '馒头' in name or '包子' in name or '饺子' in name or '馄饨' in name or '煎饼' in name or '年糕' in name or '粽子' in name or '卷' in name or '米线' in name or '花卷' in name or '油条' in name:
        return '主食'
    if '素菜' in tag_list or '凉菜' in tag_list:
        return '素菜'
    # 含肉的为荤菜
    if any(k in name for k in ['肉', '鸡', '鸭', '鱼', '虾', '牛', '羊', '排', '蛋', '三文鱼', '鸽']):
        return '荤菜'
    return '素菜'


